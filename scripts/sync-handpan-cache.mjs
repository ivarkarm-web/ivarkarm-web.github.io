#!/usr/bin/env node
/**
 * Sync Pionier service-worker SHELL + CACHE_VERSION with index.html and
 * pionier-app.js version stamps.
 *
 * Usage:
 *   node scripts/sync-handpan-cache.mjs          # write sw.js + VERSION.txt
 *   node scripts/sync-handpan-cache.mjs --check  # exit 1 if out of sync
 *
 * Single source of truth for the cache generation:
 *   handpan-app/APP_VERSION  (integer, e.g. 104 → CACHE_VERSION pionier-v104)
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const appDir = path.join(root, 'handpan-app');
const checkOnly = process.argv.includes('--check');

const APP_VERSION_PATH = path.join(appDir, 'APP_VERSION');
const INDEX_PATH = path.join(appDir, 'index.html');
const APP_JS_PATH = path.join(appDir, 'pionier-app.js');
const CORE_JS_PATH = path.join(appDir, 'pionier-core.js');
const SW_PATH = path.join(appDir, 'sw.js');
const VERSION_TXT_PATH = path.join(appDir, 'VERSION.txt');

const EXTRA_SHELL = [
  './',
  './index.html',
  './manifest.webmanifest',
  './icon.svg',
  './registerSW.js',
  './js/instrument.js',
  './js/gesture.js',
  './js/fx.js',
  './js/note-sample-bank.js',
  './js/loop-core.js',
  './js/app-state.js?v=1',
  './js/audio-core.js?v=2',
  './js/pionier-surface.js?v=146',
  './js/instruments/handpan-scales.js?v=6',
  './js/pad-layout.js?v=2',
  './pionier-core-base.js?v=1',
  './og-pionier-synth.svg',
];

function read(file) {
  if (!fs.existsSync(file)) {
    console.error('Missing file:', path.relative(root, file));
    process.exit(1);
  }
  return fs.readFileSync(file, 'utf8');
}

function extractVersionedRefs(source) {
  const found = new Set();
  const re = /(?:href|src)=["'](\.\/[^"']+\?v=\d+)["']/g;
  let m;
  while ((m = re.exec(source))) found.add(m[1]);
  return found;
}

function extractDynamicImports(source) {
  const found = new Set();
  const patterns = [
    /new URL\(\s*['"](\.\/[^'"]+)['"]/g,
    /import\(\s*['"](\.\/[^'"]+)['"]/g,
    /from\s+['"](\.\/[^'"]+)['"]/g,
  ];
  for (const re of patterns) {
    let m;
    while ((m = re.exec(source))) {
      const p = m[1];
      if (p.endsWith('.js') || p.endsWith('.css') || p.includes('?v=')) {
        found.add(p.startsWith('./') ? p : './' + p);
      }
    }
  }
  return found;
}

function normalizeShellEntry(entry) {
  let e = entry.trim();
  if (!e.startsWith('./') && e !== './') e = './' + e.replace(/^\//, '');
  return e;
}

function buildShell(indexHtml, appJs, coreJs) {
  const shell = new Set();
  for (const e of EXTRA_SHELL) shell.add(normalizeShellEntry(e));
  for (const e of extractVersionedRefs(indexHtml)) shell.add(normalizeShellEntry(e));
  for (const e of extractDynamicImports(appJs)) shell.add(normalizeShellEntry(e));
  if (coreJs) {
    for (const e of extractDynamicImports(coreJs)) shell.add(normalizeShellEntry(e));
  }
  const priority = ['./', './index.html', './manifest.webmanifest', './icon.svg'];
  const rest = [...shell].filter((e) => !priority.includes(e)).sort();
  return [...priority.filter((e) => shell.has(e)), ...rest];
}

function readAppVersion() {
  const raw = read(APP_VERSION_PATH).trim();
  const n = Number.parseInt(raw, 10);
  if (!Number.isFinite(n) || n < 1) {
    console.error('handpan-app/APP_VERSION must be a positive integer, got:', raw);
    process.exit(1);
  }
  return n;
}

function renderSw(cacheVersion, shell) {
  const L = [];
  const p = (s) => L.push(s);
  p('/**');
  p(' * Pionier service worker');
  p(' * CACHE_VERSION and SHELL query stamps MUST match index.html / pionier-app.js.');
  p(' * Generated by scripts/sync-handpan-cache.mjs \u2014 do not hand-edit SHELL.');
  p(' * Bump handpan-app/APP_VERSION then run: npm run sync:handpan');
  p(' *');
  p(' * Strategy:');
  p(' *  - HTML / navigations: network-first (fallback to cached index offline)');
  p(' *  - Versioned shell assets (?v=): network-first when online, cache fallback');
  p(' *  - Other same-origin GET: cache-first, then network');
  p(' *  - On activate: drop all caches except current CACHE_VERSION');
  p(' * Offline readiness: shell + core modules must be listed in SHELL and pre-cached on install.');
  p(' */');
  p("const CACHE_VERSION = '" + cacheVersion + "';");
  p('');
  p('const SHELL = [');
  for (const e of shell) p("  '" + e + "',");
  p('];');
  p('');
  p("self.addEventListener('install', (event) => {");
  p('  event.waitUntil((async () => {');
  p('    const cache = await caches.open(CACHE_VERSION);');
  p('    await Promise.all(SHELL.map(async (url) => {');
  p('      try {');
  p("        const res = await fetch(url, { cache: 'no-cache' });");
  p('        if (res && res.ok) await cache.put(url, res);');
  p('      } catch (_) {}');
  p('    }));');
  p('    await self.skipWaiting();');
  p('  })());');
  p('});');
  p('');
  p("self.addEventListener('activate', (event) => {");
  p('  event.waitUntil((async () => {');
  p('    const keys = await caches.keys();');
  p('    await Promise.all(keys.filter((k) => k !== CACHE_VERSION).map((k) => caches.delete(k)));');
  p('    await self.clients.claim();');
  p('  })());');
  p('});');
  p('');
  p("self.addEventListener('message', (event) => {");
  p("  if (event.data && event.data.type === 'SKIP_WAITING') self.skipWaiting();");
  p('});');
  p('');
  p('function isDocumentRequest(req, url) {');
  p("  if (req.mode === 'navigate') return true;");
  p("  if (req.destination === 'document') return true;");
  p('  const path = url.pathname;');
  p("  return path.endsWith('.html') || path.endsWith('/') || path.endsWith('/handpan-app');");
  p('}');
  p('');
  p('function isVersionedAsset(url) {');
  p("  return url.search.includes('v=');");
  p('}');
  p('');
  p("self.addEventListener('fetch', (event) => {");
  p('  const req = event.request;');
  p("  if (req.method !== 'GET') return;");
  p('  const url = new URL(req.url);');
  p('  if (url.origin !== self.location.origin) return;');
  p('');
  p('  if (isDocumentRequest(req, url)) {');
  p('    event.respondWith(');
  p('      fetch(req)');
  p('        .then((res) => {');
  p('          if (res && res.ok) {');
  p('            const copy = res.clone();');
  p('            caches.open(CACHE_VERSION).then((c) => c.put(req, copy)).catch(() => {});');
  p('          }');
  p('          return res;');
  p('        })');
  p("        .catch(() => caches.match(req).then((r) => r || caches.match('./index.html')))");
  p('    );');
  p('    return;');
  p('  }');
  p('');
  p("  if (isVersionedAsset(url) && (url.pathname.endsWith('.js') || url.pathname.endsWith('.css'))) {");
  p('    event.respondWith(');
  p('      fetch(req)');
  p('        .then((res) => {');
  p('          if (res && res.ok) {');
  p('            const copy = res.clone();');
  p('            caches.open(CACHE_VERSION).then((c) => c.put(req, copy)).catch(() => {});');
  p('          }');
  p('          return res;');
  p('        })');
  p('        .catch(() => caches.match(req))');
  p('    );');
  p('    return;');
  p('  }');
  p('');
  p('  event.respondWith(');
  p('    caches.match(req).then((cached) => {');
  p('      if (cached) return cached;');
  p('      return fetch(req).then((res) => {');
  p("        if (res && res.status === 200 && res.type !== 'opaque') {");
  p('          const copy = res.clone();');
  p('          caches.open(CACHE_VERSION).then((c) => c.put(req, copy)).catch(() => {});');
  p('        }');
  p('        return res;');
  p('      });');
  p('    })');
  p('  );');
  p('});');
  p('');
  return L.join('\n');
}

function extractCacheVersion(swSource) {
  const m = swSource.match(/const CACHE_VERSION\s*=\s*['"]([^'"]+)['"]/);
  return m ? m[1] : null;
}

function extractShell(swSource) {
  const m = swSource.match(/const SHELL\s*=\s*\[([\s\S]*?)\];/);
  if (!m) return null;
  const entries = [];
  const re = /['"]([^'"]+)['"]/g;
  let x;
  while ((x = re.exec(m[1]))) entries.push(x[1]);
  return entries;
}

function main() {
  const versionNum = readAppVersion();
  const cacheVersion = 'pionier-v' + versionNum;
  const indexHtml = read(INDEX_PATH);
  const appJs = read(APP_JS_PATH);
  const coreJs = fs.existsSync(CORE_JS_PATH) ? read(CORE_JS_PATH) : '';
  const shell = buildShell(indexHtml, appJs, coreJs);
  const nextSw = renderSw(cacheVersion, shell);

  if (checkOnly) {
    const current = read(SW_PATH);
    const curVer = extractCacheVersion(current);
    const curShell = extractShell(current);
    let ok = true;
    if (curVer !== cacheVersion) {
      console.error('CACHE_VERSION mismatch: sw has ' + curVer + ', expected ' + cacheVersion);
      ok = false;
    }
    if (JSON.stringify(curShell) !== JSON.stringify(shell)) {
      console.error('SHELL list mismatch between sw.js and index/app imports.');
      const curSet = new Set(curShell || []);
      const nextSet = new Set(shell);
      for (const e of shell) if (!curSet.has(e)) console.error('  missing in sw:', e);
      for (const e of curShell || []) if (!nextSet.has(e)) console.error('  extra in sw:', e);
      ok = false;
    }
    if (!ok) {
      console.error('\nRun: npm run sync:handpan');
      process.exit(1);
    }
    console.log('OK \u00b7 ' + cacheVersion + ' \u00b7 ' + shell.length + ' shell entries');
    return;
  }

  fs.writeFileSync(SW_PATH, nextSw);
  const today = new Date().toISOString().slice(0, 10);
  fs.writeFileSync(
    VERSION_TXT_PATH,
    [
      cacheVersion,
      today,
      'shell: ' + shell.length + ' entries (synced from index.html + pionier-app.js)',
      'run: npm run sync:handpan after changing ?v= stamps or APP_VERSION',
      '',
    ].join('\n')
  );

  console.log('Wrote ' + path.relative(root, SW_PATH));
  console.log('Wrote ' + path.relative(root, VERSION_TXT_PATH));
  console.log('CACHE_VERSION=' + cacheVersion);
  console.log('SHELL entries: ' + shell.length);
}

main();
