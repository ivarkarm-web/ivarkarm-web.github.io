#!/usr/bin/env node
/**
 * Sync Pionier service-worker SHELL with Vite build output.
 *
 * Reads dist/assets/ for hashed JS/CSS files and handpan-app/index.html
 * for the entry point. Generates sw.js with a cache-first strategy for
 * hashed assets and network-first for HTML.
 *
 * Usage:
 *   node scripts/sync-handpan-cache.mjs          # write sw.js
 *   node scripts/sync-handpan-cache.mjs --check  # exit 1 if out of sync
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const appDir = path.join(root, 'handpan-app');
const distAssets = path.join(root, 'dist', 'assets');
const swPath = path.join(appDir, 'sw.js');
const checkOnly = process.argv.includes('--check');

const APP_VERSION_PATH = path.join(appDir, 'APP_VERSION');

function readAppVersion() {
  const raw = fs.readFileSync(APP_VERSION_PATH, 'utf8').trim();
  const n = Number.parseInt(raw, 10);
  if (!Number.isFinite(n) || n < 1) {
    console.error('handpan-app/APP_VERSION must be a positive integer, got:', raw);
    process.exit(1);
  }
  return n;
}

function collectHashAssets() {
  if (!fs.existsSync(distAssets)) {
    console.error('dist/assets/ not found. Run: npm run build');
    process.exit(1);
  }
  const files = fs.readdirSync(distAssets);
  return files
    .filter((f) => f.endsWith('.js') || f.endsWith('.css'))
    .map((f) => './assets/' + f)
    .sort();
}

function renderSw(cacheVersion, shellAssets) {
  const L = [];
  const p = (s) => L.push(s);
  p('/**');
  p(' * Pionier service worker');
  p(' * Generated by scripts/sync-handpan-cache.mjs \u2014 do not hand-edit.');
  p(' * Bump handpan-app/APP_VERSION then run: npm run sync:handpan');
  p(' *');
  p(' * Strategy:');
  p(' *  - HTML / navigations: network-first (fallback to cached index)');
  p(' *  - Hashed assets (./assets/*): cache-first, immutable');
  p(' *  - Other same-origin GET: cache-first, then network');
  p(' *  - On activate: drop all caches except current CACHE_VERSION');
  p(' */');
  p('');
  p("const CACHE_VERSION = '" + cacheVersion + "';");
  p('');
  p('const ASSETS = [');
  for (const a of shellAssets) {
    p("  '" + a + "',");
  }
  p('];');
  p('');
  p("const HTML_SHELL = ['.', './index.html'];");
  p('');
  p("self.addEventListener('install', (event) => {");
  p('  event.waitUntil((async () => {');
  p('    const cache = await caches.open(CACHE_VERSION);');
  p('    // Pre-cache hashed assets (immutable, cache-first)');
  p('    let failed = [];');
  p('    await Promise.all(ASSETS.map(async (url) => {');
  p('      try {');
  p("        const res = await fetch(url, { cache: 'no-cache' });");
  p('        if (res && res.ok) await cache.put(url, res); else failed.push(url);');
  p('      } catch (_) { failed.push(url); }');
  p('    }));');
  p('    if (failed.length > 0) throw new Error("SW install failed: " + failed.join(","));');
  p('    await self.skipWaiting();');
  p('  }));');
  p('});');
  p('');
  p("self.addEventListener('activate', (event) => {");
  p('  event.waitUntil((async () => {');
  p('    const keys = await caches.keys();');
  p('    await Promise.all(keys.filter((k) => k !== CACHE_VERSION).map((k) => caches.delete(k)));');
  p('    await self.clients.claim();');
  p('  }));');
  p('});');
  p('');
  p("self.addEventListener('fetch', (event) => {");
  p('  const req = event.request;');
  p("  if (req.method !== 'GET') return;");
  p('  const url = new URL(req.url);');
  p('  if (url.origin !== self.location.origin) return;');
  p('');
  p('  // HTML / navigations: network-first, cache fallback');
  p('  const isDoc =');
  p("    req.mode === 'navigate' ||");
  p("    req.destination === 'document' ||");
  p("    url.pathname.endsWith('.html') ||");
  p("    url.pathname.endsWith('/') ||");
  p("    url.pathname.endsWith('/handpan-app');");
  p('');
  p('  if (isDoc) {');
  p('    event.respondWith(');
  p('      fetch(req)');
  p('        .then((res) => {');
  p('          if (res && res.ok) {');
  p('            const copy = res.clone();');
  p('            caches.open(CACHE_VERSION).then((c) => c.put(req, copy)).catch(() => {});');
  p('          }');
  p('          return res;');
  p('        })');
  p("        .catch(() => caches.match(req).then((r) => r || caches.match('./index.html')))");
  p('    );');
  p('    return;');
  p('  }');
  p('');
  p('  // Hashed assets: cache-first, immutable');
  p("  const isAsset = url.pathname.startsWith('/assets/');");
  p('  if (isAsset) {');
  p('    event.respondWith(');
  p('      caches.match(req).then((cached) => {');
  p('        if (cached) return cached;');
  p('        return fetch(req).then((res) => {');
  p("          if (res && res.status === 200 && res.type !== 'opaque') {");
  p('            const copy = res.clone();');
  p('            caches.open(CACHE_VERSION).then((c) => c.put(req, copy)).catch(() => {});');
  p('          }');
  p('          return res;');
  p('        });');
  p('      })');
  p('    );');
  p('    return;');
  p('  }');
  p('');
  p('');
  p('  // Other same-origin GET: cache-first, then network');
  p('  event.respondWith(');
  p('    caches.match(req).then((cached) => {');
  p('      if (cached) return cached;');
  p('      return fetch(req).then((res) => {');
  p("        if (res && res.status === 200 && res.type !== 'opaque') {");
  p('          const copy = res.clone();');
  p('          caches.open(CACHE_VERSION).then((c) => c.put(req, copy)).catch(() => {});');
  p('        }');
  p('        return res;');
  p('        });');
  p('      })');
  p('    );');
  p('  });');
  p('');
  return L.join('\n');
}

function main() {
  const versionNum = readAppVersion();
  const cacheVersion = 'pionier-v' + versionNum;
  const shellAssets = collectHashAssets();
  const nextSw = renderSw(cacheVersion, shellAssets);

  if (checkOnly) {
    const current = fs.readFileSync(swPath, 'utf8');
    const curVer = current.match(/const CACHE_VERSION\s*=\s*['"]([^'"]+)['"]/);
    const curAssets = [];
    const re = /['"](\.\/assets\/[^'"]+)['"]/g;
    let m;
    while ((m = re.exec(current))) curAssets.push(m[1]);
    curAssets.sort();

    let ok = true;
    if ((curVer && curVer[1]) !== cacheVersion) {
      console.error(
        'CACHE_VERSION mismatch: sw has ' + (curVer && curVer[1]) + ', expected ' + cacheVersion
      );
      ok = false;
    }
    const curSorted = curAssets.slice().sort();
    const nextSorted = shellAssets.slice().sort();
    if (JSON.stringify(curSorted) !== JSON.stringify(nextSorted)) {
      console.error('ASSETS mismatch between sw.js and dist/assets/.');
      ok = false;
    }
    if (!ok) {
      console.error('\nRun: npm run sync:handpan');
      process.exit(1);
    }
    console.log('OK \u00b7 ' + cacheVersion + ' \u00b7 ' + shellAssets.length + ' hashed assets');
    return;
  }

  fs.writeFileSync(swPath, nextSw);
  console.log('Wrote ' + path.relative(root, swPath));
  console.log('CACHE_VERSION=' + cacheVersion);
  console.log('Hashed assets: ' + shellAssets.length);
}

main();
